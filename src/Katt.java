public class Katt {
    private String name;
    private int chipNumber;
    private String breed;

    public Katt(String name, int chipNumber, String breed) {
        this.name = name;
        this.chipNumber = chipNumber;
        this.breed = breed;
    }
    public String getName() {
        return name;
    }
    public int getChipNumber() {
        return chipNumber;
    }
    public String getBreed() {
        return breed;
    }
}
